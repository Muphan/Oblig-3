def roll_d100():
    """Kjører en rulle-animasjon i konsollen og returnerer sluttresultatet."""
    for i in range(12):
        os.system("cls" if os.name == "nt" else "clear")
        temp_roll = random.randint(0, 100)
        print(render_d100(temp_roll))
        time.sleep(0.04 + (i * 0.012))  # Sakker av mot slutten

    final_roll = random.randint(0, 100)
    os.system("cls" if os.name == "nt" else "clear")
    print(render_d100(final_roll))
    print(f"\n>>> DU RULLET: {final_roll} / 100 <<<\n")


def main():
    while True:
        roll_d100()

        # Spør brukeren om nytt rull
        user_choice = input(
            "Trykk Enter (eller en hvilken som helst knapp) for å rulle igjen, [q] for å avslutte: "
        ).strip().lower()

        # Sjekker kun om brukeren skrev 'q' eller 'quit'
        if user_choice in ["q", "quit"]:
            print("\nTakk for kastet!")
            break


if __name__ == "__main__":
    main()

